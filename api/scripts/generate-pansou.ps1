param([switch]$Check)
$ErrorActionPreference = 'Stop'
$repo = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$submodule = Join-Path $repo 'third_party/pansou'
$main = Get-Content (Join-Path $submodule 'main.go')
$names = @($main | ForEach-Object { if ($_ -match '^\s*_\s+"pansou/plugin/([^"]+)"') { $Matches[1] } } | Sort-Object -Unique)
if ($names.Count -eq 0) { throw 'No active PanSou plugin imports found.' }
$compose = Get-Content (Join-Path $submodule 'docker-compose.yml') -Raw
if ($compose -notmatch '(?m)^\s*-\s*CHANNELS=([^\r\n]+)') { throw 'Upstream recommended channels not found.' }
$channels = $Matches[1].Trim().Trim('"')
if ($compose -notmatch '(?m)^\s*-\s*ENABLED_PLUGINS=([^\r\n]+)') { throw 'Upstream recommended plugins not found.' }
$plugins = @($Matches[1].Trim().Trim('"').Split(',') | Where-Object { $_ -in $names }) -join ','
if (-not $plugins) { throw 'Recommended plugins do not match compiled imports.' }
foreach ($name in ($channels.Split(',') + $plugins.Split(','))) { if ($name -notmatch '^[a-zA-Z0-9_-]{1,24}$') { throw "Invalid upstream source name: $name" } }
$revision = git -C $submodule rev-parse HEAD
if ($LASTEXITCODE -ne 0) { throw 'Cannot read pinned PanSou revision.' }
$header = '// Code generated by scripts/generate-pansou.ps1; DO NOT EDIT.'
$imports = @($header, 'package pansoubridge', '', 'import (') + @($names | ForEach-Object { ' _ "pansou/plugin/' + $_ + '"' }) + @(')', '')
$defaults = @($header, 'package pansoubridge', '', ('const recommendedChannels = "' + $channels + '"'), ('const recommendedPlugins = "' + $plugins + '"'), ('const embeddedPanSouCommit = "' + $revision + '"'), '')
foreach ($entry in @(@{ Path = 'internal/pansoubridge/plugins_generated.go'; Lines = $imports }, @{ Path = 'internal/pansoubridge/defaults_generated.go'; Lines = $defaults })) {
    $formatted = ($entry.Lines | gofmt) -join "`n"
    if ($LASTEXITCODE -ne 0) { throw 'gofmt failed.' }
    $target = Join-Path $repo $entry.Path
    if ($Check) {
        if (-not (Test-Path -LiteralPath $target) -or [IO.File]::ReadAllText($target).Replace("`r`n", "`n").Trim() -ne $formatted.Trim()) { throw "Generated PanSou data is stale: $($entry.Path). Run scripts/generate-pansou.ps1." }
    } else { [IO.File]::WriteAllText($target, $formatted + "`n", [Text.UTF8Encoding]::new($false)) }
}
Write-Host "Verified $($names.Count) imports and pinned defaults from PanSou $revision."